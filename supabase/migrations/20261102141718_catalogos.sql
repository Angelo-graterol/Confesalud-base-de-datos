-- 1. Tabla de departamentos
CREATE TABLE public.states (
    id INTEGER PRIMARY KEY,
    state_name VARCHAR(50) NOT NULL
);

-- 2. Tabla de ciudades
CREATE TABLE public.cities (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    city_name VARCHAR(60) NOT NULL,
    state_id INTEGER NOT NULL,

    CONSTRAINT fk_cities_states
        FOREIGN KEY (state_id)
        REFERENCES public.states(id),

    CONSTRAINT uq_cities_name_state
        UNIQUE (city_name, state_id)
);

-- 3. Tabla de eps
CREATE TABLE public.eps (
    id INTEGER PRIMARY KEY,
    eps_name VARCHAR(100) NOT NULL,
    nit VARCHAR(15) NOT NULL UNIQUE,
    phone VARCHAR(15),
    email VARCHAR(100)
);

-- 4. Tipos de orden médica
CREATE TABLE public.order_types (
    id          INTEGER      NOT NULL,
    type_name   VARCHAR(50)  NOT NULL,
    description VARCHAR(200),

    CONSTRAINT pk_order_types PRIMARY KEY (id)
);

-- 5. Órdenes médicas
-- Cascada
CREATE TABLE public.medical_orders (
    id              INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    order_number    VARCHAR(20)  NOT NULL,
    issue_date      DATE         NOT NULL DEFAULT CURRENT_DATE,
    expiration_date DATE         NOT NULL,
    order_status    VARCHAR(15)  NOT NULL DEFAULT 'VIGENTE',
    ote_id          INTEGER      NOT NULL,

    CONSTRAINT pk_medical_orders PRIMARY KEY (id),
    CONSTRAINT uq_medical_orders_number UNIQUE (order_number),
    CONSTRAINT ck_medical_orders_dates
        CHECK (expiration_date >= issue_date),
    CONSTRAINT ck_medical_orders_status
        CHECK (order_status IN ('VIGENTE', 'USADA', 'VENCIDA', 'ANULADA')),
    CONSTRAINT fk_medical_orders_order_types
        FOREIGN KEY (ote_id)
        REFERENCES public.order_types(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- 6. Especialidades
CREATE TABLE public.specialties (
    id               INTEGER     NOT NULL,
    specialty_name   VARCHAR(60) NOT NULL,
    specialty_status VARCHAR(15) NOT NULL DEFAULT 'ACTIVA',

    CONSTRAINT pk_specialties PRIMARY KEY (id),
    CONSTRAINT uq_specialties_name UNIQUE (specialty_name),
    CONSTRAINT ck_specialties_status
        CHECK (specialty_status IN ('ACTIVA', 'INACTIVA'))
);
