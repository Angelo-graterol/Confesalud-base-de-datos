-- ============================================
-- Migración: citas
-- Tablas: appointments, cancellations
-- Depende de: catalogos (medical_orders), personas (clients, doctors, staffs)
-- ============================================
 
-- 1. Citas
CREATE TABLE public.appointments (
    id                 INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    request_date       TIMESTAMP    NOT NULL DEFAULT now(),
    assignment_date    TIMESTAMP    NOT NULL,
    arrival_time       TIMESTAMP,
    channel            VARCHAR(20)  NOT NULL,
    appointment_status VARCHAR(15)  NOT NULL DEFAULT 'PROGRAMADA',
    observation        VARCHAR(300),
    cet_id             INTEGER      NOT NULL,
    dtr_id             INTEGER      NOT NULL,
    stf_id             INTEGER      NOT NULL,
    mor_id             INTEGER,
 
    CONSTRAINT pk_appointments PRIMARY KEY (id),
 
    CONSTRAINT ck_appointments_dates
        CHECK (assignment_date >= request_date),
    CONSTRAINT ck_appointments_arrival
        CHECK (arrival_time IS NULL OR arrival_time >= request_date),
    CONSTRAINT ck_appointments_channel
        CHECK (channel IN ('PRESENCIAL', 'TELEFONO', 'WEB')),
    CONSTRAINT ck_appointments_status
        CHECK (appointment_status IN ('PROGRAMADA', 'ATENDIDA', 'CANCELADA', 'INASISTENCIA')),
 
    CONSTRAINT fk_appointments_clients
        FOREIGN KEY (cet_id) REFERENCES public.clients(id),
    CONSTRAINT fk_appointments_doctors
        FOREIGN KEY (dtr_id) REFERENCES public.doctors(id),
    CONSTRAINT fk_appointments_staffs
        FOREIGN KEY (stf_id) REFERENCES public.staffs(id),
 
    -- Cascada, se borran o actualizan las citas que dependen de ella.
    CONSTRAINT fk_appointments_medical_orders
        FOREIGN KEY (mor_id) REFERENCES public.medical_orders(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);
 
-- 2. Cancelaciones 
CREATE TABLE public.cancellations (
    id                INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    cancellation_date TIMESTAMP    NOT NULL DEFAULT now(),
    reason            VARCHAR(200) NOT NULL,
    cancelled_by      VARCHAR(30)  NOT NULL,
    apt_id            INTEGER      NOT NULL,
    stf_id            INTEGER      NOT NULL,
 
    CONSTRAINT pk_cancellations PRIMARY KEY (id),
    CONSTRAINT uq_cancellations_apt UNIQUE (apt_id),
    CONSTRAINT ck_cancellations_by
        CHECK (cancelled_by IN ('PACIENTE', 'MEDICO', 'ADMINISTRATIVO')),
 
    -- También en cascada
    CONSTRAINT fk_cancellations_appointments
        FOREIGN KEY (apt_id) REFERENCES public.appointments(id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_cancellations_staffs
        FOREIGN KEY (stf_id) REFERENCES public.staffs(id)
);
 
-- Índices para las FK (Postgres no los crea solo y ayudan en los JOIN)
CREATE INDEX ix_appointments_cet_id ON public.appointments (cet_id);
CREATE INDEX ix_appointments_dtr_id ON public.appointments (dtr_id);
CREATE INDEX ix_appointments_stf_id ON public.appointments (stf_id);
CREATE INDEX ix_appointments_mor_id ON public.appointments (mor_id);
CREATE INDEX ix_cancellations_stf_id ON public.cancellations (stf_id);
