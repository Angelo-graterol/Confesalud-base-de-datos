-- ============================================
-- Migración: personas
-- Tablas: doctors, staffs, doctor_specialties, clients
-- Depende de: catalogos (specialties, eps, cities)
-- ============================================
 
-- 1. Médicos
CREATE TABLE public.doctors (
    id                   INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    first_name           VARCHAR(30)  NOT NULL,
    second_name          VARCHAR(30),
    last_name            VARCHAR(30)  NOT NULL,
    second_last_name     VARCHAR(30),
    document_type        VARCHAR(5)   NOT NULL,
    document_number      VARCHAR(20)  NOT NULL,
    medical_registration VARCHAR(20)  NOT NULL,
    signature            BYTEA,
    doctor_status        VARCHAR(15)  NOT NULL DEFAULT 'ACTIVO',
 
    CONSTRAINT pk_doctors PRIMARY KEY (id),
    CONSTRAINT uq_doctors_document UNIQUE (document_type, document_number),
    CONSTRAINT uq_doctors_medical_registration UNIQUE (medical_registration),
    CONSTRAINT ck_doctors_document_type
        CHECK (document_type IN ('CC', 'CE', 'PA', 'PPT')),
    CONSTRAINT ck_doctors_status
        CHECK (doctor_status IN ('ACTIVO', 'INACTIVO', 'VACACIONES'))
);
 
-- 2. Personal administrativo
CREATE TABLE public.staffs (
    id               INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    first_name       VARCHAR(30)  NOT NULL,
    second_name      VARCHAR(30),
    last_name        VARCHAR(30)  NOT NULL,
    second_last_name VARCHAR(30),
    document_number  VARCHAR(20)  NOT NULL,
    staff_role       VARCHAR(30)  NOT NULL,
    staff_status     VARCHAR(15)  NOT NULL DEFAULT 'ACTIVO',
 
    CONSTRAINT pk_staffs PRIMARY KEY (id),
    CONSTRAINT uq_staffs_document UNIQUE (document_number),
    CONSTRAINT ck_staffs_role
        CHECK (staff_role IN ('RECEPCIONISTA', 'AUXILIAR', 'COORDINADOR', 'ADMINISTRADOR')),
    CONSTRAINT ck_staffs_status
        CHECK (staff_status IN ('ACTIVO', 'INACTIVO'))
);
 
-- 3. Especialidades de cada médico (relación muchos a muchos)
CREATE TABLE public.doctor_specialties (
    dtr_id     INTEGER NOT NULL,
    scy_id     INTEGER NOT NULL,
    start_date DATE    NOT NULL DEFAULT CURRENT_DATE,
 
    CONSTRAINT pk_doctor_specialties PRIMARY KEY (dtr_id, scy_id),
    -- Si se borra el médico, se borran sus especialidades asignadas
    CONSTRAINT fk_doctor_specialties_doctors
        FOREIGN KEY (dtr_id) REFERENCES public.doctors(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_doctor_specialties_specialties
        FOREIGN KEY (scy_id) REFERENCES public.specialties(id)
);
 
-- 4. Clientes (pacientes)
CREATE TABLE public.clients (
    id                 INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    first_name         VARCHAR(30)  NOT NULL,
    second_name        VARCHAR(30),
    last_name          VARCHAR(30)  NOT NULL,
    second_last_name   VARCHAR(30),
    document_type      VARCHAR(5)   NOT NULL,
    document_number    VARCHAR(20)  NOT NULL,
    gender             CHAR(1)      NOT NULL,
    birth_date         DATE         NOT NULL,
    phone              VARCHAR(15),
    email              VARCHAR(100),
    address            VARCHAR(100),
    zone               VARCHAR(10)  NOT NULL DEFAULT 'URBANA',
    regime             VARCHAR(20)  NOT NULL,
    affiliation_status VARCHAR(15)  NOT NULL DEFAULT 'ACTIVO',
    occupation         VARCHAR(50),
    education_level    VARCHAR(30),
    eps_id             INTEGER      NOT NULL,
    city_id            INTEGER      NOT NULL,
 
    CONSTRAINT pk_clients PRIMARY KEY (id),
    CONSTRAINT uq_clients_document UNIQUE (document_type, document_number),
    CONSTRAINT ck_clients_document_type
        CHECK (document_type IN ('CC', 'TI', 'RC', 'CE', 'PA', 'PPT')),
    CONSTRAINT ck_clients_gender
        CHECK (gender IN ('M', 'F', 'O')),
    CONSTRAINT ck_clients_birth_date
        CHECK (birth_date <= CURRENT_DATE),
    CONSTRAINT ck_clients_zone
        CHECK (zone IN ('URBANA', 'RURAL')),
    CONSTRAINT ck_clients_regime
        CHECK (regime IN ('CONTRIBUTIVO', 'SUBSIDIADO', 'ESPECIAL')),
    CONSTRAINT ck_clients_affiliation_status
        CHECK (affiliation_status IN ('ACTIVO', 'SUSPENDIDO', 'RETIRADO')),
    CONSTRAINT fk_clients_eps
        FOREIGN KEY (eps_id) REFERENCES public.eps(id),
    CONSTRAINT fk_clients_cities
        FOREIGN KEY (city_id) REFERENCES public.cities(id)
);
 
-- Índices para las FK
CREATE INDEX ix_doctor_specialties_scy_id ON public.doctor_specialties (scy_id);
CREATE INDEX ix_clients_eps_id  ON public.clients (eps_id);
CREATE INDEX ix_clients_city_id ON public.clients (city_id);